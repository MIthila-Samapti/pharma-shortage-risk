"""Builds the dataset docs/risk-map.html runs on.

Mirrors build_site_data.py's pattern exactly: writes plain JS
(window.RX_CONCENTRATION = [...]) so the static site can just
<script src> it, no server or CORS needed - same reasoning, same
file shape, just a different source table (concentration_map.py's
at-risk list instead of the scored shortage list).

Only the at-risk rows (single/dual-source, not already shortage-
listed) are written to the site - the full concentration table for
every drug is useful for debugging but would bloat the page for no
reader benefit.
"""

import json

from concentration_map import build
from data_prep import latest_snapshot_path, snapshot_date_from_path


def to_record(row):
    return {
        "generic_name": row["generic_name"],
        "dosage_form": row["dosage_form"],
        "route": row["route"] if isinstance(row["route"], str) else None,
        "product_type": row["product_type"] if isinstance(row["product_type"], str) else None,
        "labeler_count": int(row["labeler_count"]),
        "labelers": row["labelers"],
        "risk_tier": row["risk_tier"],
    }


def build_records():
    shortages_path = latest_snapshot_path()
    snapshot_date = snapshot_date_from_path(shortages_path) if shortages_path else None
    _, flagged = build(shortages_path=shortages_path)
    records = [to_record(r) for _, r in flagged.iterrows()]
    return records, snapshot_date


if __name__ == "__main__":
    import os

    records, snapshot_date = build_records()
    as_of = snapshot_date.date().isoformat() if snapshot_date is not None else ""
    os.makedirs("docs/data", exist_ok=True)
    with open("docs/data/concentration.js", "w") as f:
        f.write("// Auto-generated by src/build_concentration_data.py - do not hand-edit\n")
        f.write("window.RX_CONCENTRATION = ")
        json.dump(records, f, indent=1)
        f.write(";\n")
        f.write('window.RX_CONCENTRATION_AS_OF = "' + as_of + '";\n')
    print(f"wrote docs/data/concentration.js: {len(records)} at-risk (generic_name, dosage_form) profiles")
    single = sum(1 for r in records if r["risk_tier"] == "single-source")
    dual = sum(1 for r in records if r["risk_tier"] == "dual-source")
    print(f"single-source: {single}, dual-source: {dual}")
